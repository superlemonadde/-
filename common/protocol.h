#ifndef PROTOCOL_H
#define PROTOCOL_H

/* ============================================================
 * protocol.h
 * 协议公共定义：包结构、常量、模式标识
 *
 * 本文件被 client/ 和 server/ 共同引用，修改时需保持两端一致。
 * ============================================================ */

/* ------------------------------------------------------------
 * 单个数据单元（DU）大小，单位：字节
 * 可选值：256 / 512 / 1024 / 2048
 * 修改后需重新编译全部源文件。
 * ------------------------------------------------------------ */
#define DU_SIZE 1024

/* ------------------------------------------------------------
 * 服务器监听端口
 * ------------------------------------------------------------ */
#define SERVER_PORT 8888

/* ------------------------------------------------------------
 * 服务器 IP（本地回环，用于单机测试）
 * 若部署到真实网络，改为对应 IP 字符串。
 * ------------------------------------------------------------ */
#define SERVER_IP "127.0.0.1"

/* ------------------------------------------------------------
 * 传输模式标识
 *   MODE_VARIABLE : 可变批大小，按 1->2->3->1->... 循环
 *   MODE_FIXED    : 固定批大小，每批固定发送 2 个 DU
 * ------------------------------------------------------------ */
#define MODE_VARIABLE 1
#define MODE_FIXED    2

/* ------------------------------------------------------------
 * 数据包（DU）结构
 *
 * 字段说明：
 *   seq     : 包序号，从 0 开始单调递增，用于调试和 ACK 确认
 *   length  : 本包中有效数据的字节数
 *             - 普通包：实际读到的字节数（≤ DU_SIZE）
 *             - 最后包：最后一次 fread 读到的字节数（可能 < DU_SIZE）
 *             - 结束标志包（is_last=1 且 length=0）：无数据
 *   is_last : 是否为最后一个包
 *             0 = 普通包，1 = 最后一个包
 *   mode    : 传输模式（MODE_VARIABLE / MODE_FIXED）
 *             随每个包携带，使服务端无需额外握手即可识别模式。
 *   data    : 数据内容，固定 DU_SIZE 字节
 *             不足时由发送端补 0，接收端按 length 截断写入。
 * ------------------------------------------------------------ */
typedef struct
{
    int  seq;
    int  length;
    int  is_last;
    int  mode;
    char data[DU_SIZE];
} Packet;

/* ------------------------------------------------------------
 * ACK 确认包
 *
 * 字段说明：
 *   ack : 本次确认的最后一个包序号
 * ------------------------------------------------------------ */
typedef struct
{
    int ack;
} AckPacket;

#endif /* PROTOCOL_H */

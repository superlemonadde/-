#ifndef UTILS_H
#define UTILS_H

/* ============================================================
 * utils.h
 * 公共工具函数声明
 *
 * 提供：
 *   - 字节流 checksum 计算
 *   - 高精度时间戳（毫秒）
 *   - 文件大小查询
 * ============================================================ */

#include <stdint.h>

/* ------------------------------------------------------------
 * calculate_checksum
 *
 * 对内存中的字节数组做简单累加校验。
 *
 * 参数：
 *   data : 待校验的数据缓冲区指针
 *   len  : 缓冲区字节数
 *
 * 返回值：
 *   所有字节无符号累加的 32 位结果。
 *   发送端与接收端对相同数据调用后结果相等，即文件传输正确。
 *
 * 注意：
 *   接收端对每个包按 DU_SIZE（含补零部分）计算，
 *   发送端同样按 DU_SIZE 计算，两端口径一致才能比对。
 * ------------------------------------------------------------ */
uint32_t calculate_checksum(char *data, int len);

/* ------------------------------------------------------------
 * get_time_ms
 *
 * 获取当前时刻的 Unix 时间戳（毫秒精度）。
 * 使用 gettimeofday，反映挂钟时间（wall-clock），
 * 适合统计含网络等待的实际传输耗时。
 *
 * 返回值：自 Epoch 起的毫秒数（double）
 * ------------------------------------------------------------ */
double get_time_ms(void);

/* ------------------------------------------------------------
 * get_file_size
 *
 * 查询文件的字节大小，不改变文件内容。
 *
 * 参数：
 *   filename : 文件路径
 *
 * 返回值：
 *   成功 → 文件字节数（long，>= 0）
 *   失败 → -1（文件不存在或无权限）
 * ------------------------------------------------------------ */
long get_file_size(const char *filename);

#endif /* UTILS_H */
